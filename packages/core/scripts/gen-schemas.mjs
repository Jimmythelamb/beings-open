// Generates src/schemas.generated.ts from schemas/*.schema.json.
// The JSON files are the source of truth (extracted verbatim from spec section 11).
// Run: npm run gen:schemas -w @beings/core
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = [
  ["election-file", "electionFile"],
  ["ballot-record", "ballotRecord"],
  ["ledger-entry", "ledgerEntry"],
  ["correction", "correction"],
  ["tally", "tally"],
  ["verifier-report", "verifierReport"],
];

let out = `// GENERATED by scripts/gen-schemas.mjs from schemas/*.schema.json. Do not edit by hand.\n`;
out += `// Schemas are copied verbatim from the design spec, section 11 (draft 2020-12).\n\n`;
out += `export const SCHEMAS = {\n`;
for (const [file, key] of names) {
  const json = JSON.parse(readFileSync(join(root, "schemas", `${file}.schema.json`), "utf8"));
  out += `  ${JSON.stringify(key)}: ${JSON.stringify(json, null, 2).replace(/\n/g, "\n  ")},\n`;
}
out += `} as const;\n\nexport type SchemaName = keyof typeof SCHEMAS;\n`;
writeFileSync(join(root, "src", "schemas.generated.ts"), out);
console.log("wrote src/schemas.generated.ts");
